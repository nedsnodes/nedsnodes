#!/usr/bin/env python3
"""Tests that the cold-read fast read's scratch HOME keeps the caller's per-user site-packages.

Python finds the per-user site-packages from HOME. The fixture gives the
program under test a scratch HOME, and a pinned library installed only per
user, such as markdown-it-py, must still import there; otherwise the program
installs the pinned libraries with pip, which can time out under load.

The case runs the fixture in a child Python whose HOME is a fake home with a
module in that home's user site-packages, then imports the module under the
environment the fixture returns.
"""

import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

FIXTURE = Path(__file__).resolve().parent / "cold-read-scratch-repository-test-fixture.py"
PROBE_MODULE = "cold_read_fixture_user_site_only_probe_module"

CHILD = r'''import importlib.util, subprocess, sys
spec = importlib.util.spec_from_file_location("cold_read_scratch_repository_test_fixture", sys.argv[1])
fixture = importlib.util.module_from_spec(spec)
spec.loader.exec_module(fixture)
_, environment = fixture.cold_read_fast_read_scratch_repository_whose_stub_agy_answers_in_chat(sys.argv[2], sys.argv[3])
result = subprocess.run([sys.executable, "-c", "import " + sys.argv[4]], env=environment,
                        capture_output=True, text=True, timeout=60)
sys.stderr.write(result.stderr)
sys.exit(result.returncode)
'''


class ScratchHomeKeepsUserSitePackages(unittest.TestCase):
    def test_a_module_only_in_the_callers_user_site_imports_under_the_fixtures_environment(self):
        with tempfile.TemporaryDirectory() as temporary:
            temporary = Path(temporary)
            home = temporary / "caller-home"
            home.mkdir()
            environment = dict(os.environ, HOME=str(home))
            environment.pop("PYTHONUSERBASE", None)
            user_site = subprocess.run(
                [sys.executable, "-c", "import site; print(site.getusersitepackages())"],
                env=environment, capture_output=True, text=True, check=True, timeout=60).stdout.strip()
            Path(user_site).mkdir(parents=True)
            (Path(user_site) / f"{PROBE_MODULE}.py").write_text("", encoding="utf-8")
            result = subprocess.run(
                [sys.executable, "-c", CHILD, str(FIXTURE), str(temporary / "scratch"),
                 str(temporary / "ship-destination"), PROBE_MODULE],
                env=environment, capture_output=True, text=True, timeout=300)
            self.assertEqual(result.returncode, 0, result.stderr)


if __name__ == "__main__":
    unittest.main()
